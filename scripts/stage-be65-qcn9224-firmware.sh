# Stage user-owned BE65 QCN9224 firmware in OpenWrt's ignored files/ overlay.

set -eu

if [ "$#" -gt 2 ] || [ "$#" -lt 1 ]; then
	echo "usage: $0 STOCK_ROOT [OUTPUT_DIR]" >&2
	exit 2
fi

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_root=$(CDPATH= cd -- "$script_dir/.." && pwd)
stock_root=$1
output_dir=${2:-"$repo_root/files/lib/firmware/ath12k/QCN92XX/hw1.0"}
encoder="$script_dir/ath12k-bdencoder"
qcn_root="$stock_root/lib/firmware/IPQ5332/WIFI_FW/qcn9224"
rxgain_root="$stock_root/lib/firmware/qcn9224"
board_name='bus=pci,qmi-chip-id=0,qmi-board-id=4121'

tmp_dir=$(mktemp -d "${TMPDIR:-/tmp}/be65-qcn9224.XXXXXX")
trap 'rm -rf "$tmp_dir"' EXIT HUP INT TERM

require_file() {
	if [ ! -f "$1" ]; then
		echo "required firmware file not found: $1" >&2
		exit 1
	fi
}

hash_file() {
	if command -v sha256sum >/dev/null 2>&1; then
		sha256sum "$1"
	else
		shasum -a 256 "$1"
	fi
}

require_file "$encoder"
require_file "$qcn_root/amss_dualmac.bin"
require_file "$qcn_root/bdwlan.b1019"
require_file "$qcn_root/m3.bin"
require_file "$qcn_root/regdb.bin"
require_file "$rxgain_root/rxgainlut.b1019"

cp "$qcn_root/bdwlan.b1019" "$tmp_dir/bdwlan.b1019"
cat >"$tmp_dir/mapping.json" <<EOF
[
  {
    "board": [
      {
        "names": ["$board_name"],
        "data": "bdwlan.b1019"
      }
    ]
  }
]
EOF

(
	cd "$tmp_dir"
	python3 -I "$encoder" --create mapping.json --output board-2.bin
	python3 -I "$encoder" --info board-2.bin > board-2.info
)

grep -F "BoardNames[0]: '$board_name'" "$tmp_dir/board-2.info" >/dev/null

mkdir -p "$output_dir"
install -m 0644 "$tmp_dir/board-2.bin" "$output_dir/board-2.bin"
install -m 0644 "$qcn_root/amss_dualmac.bin" "$output_dir/amss_dualmac.bin"
install -m 0644 "$qcn_root/m3.bin" "$output_dir/m3.bin"
install -m 0644 "$qcn_root/regdb.bin" "$output_dir/regdb.bin"
install -m 0644 "$rxgain_root/rxgainlut.b1019" "$output_dir/rxgainlut.b1019"

(
	cd "$output_dir"
	{
		echo "QCN9224 board key: $board_name"
		echo "Generated by scripts/stage-be65-qcn9224-firmware.sh"
		for file in board-2.bin amss_dualmac.bin m3.bin regdb.bin rxgainlut.b1019; do
			hash_file "$file"
		done
	} > BE65-FIRMWARE-MANIFEST.txt
)

cat "$tmp_dir/board-2.info"
echo "Staged BE65 QCN9224 firmware in $output_dir"
echo "The files/ tree is ignored; do not add these proprietary payloads to git."
